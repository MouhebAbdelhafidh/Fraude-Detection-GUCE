def load_real_data() -> tuple[np.ndarray, np.ndarray, pd.DataFrame]:
    """
    Loads feature data generated by Airflow pipeline task 'pyspark_data_preparation'.
    First attempts reading data/tmp/extracted_features.pkl, then falls back to Parquet storage.
    """
    print("📂 Loading actual dataset from Airflow pipeline output...")

    pickle_path = os.path.join(PROJECT_ROOT, "data", "tmp", "extracted_features.pkl")
    parquet_path = os.path.join(PROJECT_ROOT, "data", "processed", "scaled_siat_fraud_dataset.parquet")
    alt_parquet_path = os.path.join(PROJECT_ROOT, "datamlops", "scaled_siat_fraud_dataset.parquet")

    if os.path.exists(pickle_path):
        print(f"📄 Reading Airflow task feature buffer: {pickle_path}")
        df = pd.read_pickle(pickle_path)
        X = np.array([v.toArray() if hasattr(v, "toArray") else v for v in df["scaled_features"]], dtype=np.float32)
    elif os.path.exists(parquet_path) or os.path.exists(alt_parquet_path):
        target_path = parquet_path if os.path.exists(parquet_path) else alt_parquet_path
        print(f"📄 Reading exported Parquet dataset: {target_path}")
        df = pd.read_parquet(target_path)
        
        available_features = [c for c in TARGET_18_FEATURES if c in df.columns]
        if len(available_features) == 18:
            print("🎯 Found all 18 engineered target feature columns!")
            feature_cols = available_features
        else:
            print(f"⚠️ Only found {len(available_features)}/18 exact columns. Falling back to numeric filter.")
            numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
            ignore_cols = ["file_id", "id", "user_id", "company_id", "is_anomaly", "target", "label", "fraud_label"]
            feature_cols = [c for c in numeric_cols if c not in ignore_cols]
            
        X = df[feature_cols].fillna(0).values.astype(np.float32)
    else:
        raise FileNotFoundError("❌ Could not find pipeline data! Run 'pyspark_data_preparation' first.")

    # ------------------------------------------------------------------
    # UNSUPERVISED EVALUATION SETUP
    # Since data is unlabeled, use the full dataset as the background reference X_ref.
    # High-risk evaluation targets will be filtered downstream based on ensemble risk scores.
    # ------------------------------------------------------------------
    print(f"✅ Unsupervised Dataset Loaded: {len(X)} Total Records.")
    print(f"📐 Active Input Feature Dimension: {X.shape[1]}")
    
    return X, df


def ensure_models_match_dimensions(X_full: np.ndarray, df_real: pd.DataFrame, n_features: int) -> dict:
    """
    Verifies that saved models match current feature dimension (18). Retrains any out-of-date model.
    """
    print(f"\n⚙️ Verifying model pipeline feature dimensions (Expected: {n_features})...")
    models = load_saved_models(input_dim=n_features)
    
    # 1. PyTorch Autoencoder (CRITICAL for Gradient Attacks!)
    ae_model = models.get("autoencoder")
    if ae_model is None:
        print("⚠️ Retraining PyTorch Autoencoder to match 18-feature dataset dimensions...")
        df_real = train_pytorch_autoencoder(X_full, df_real.copy(), n_trials=5)

    # 2. One-Class SVM
    ocsvm = models.get("ocsvm")
    if ocsvm is None or getattr(ocsvm, "n_features_in_", None) != n_features:
        print("⚠️ Retraining One-Class SVM to match dataset dimensions...")
        df_real = train_sgd_one_class_svm(X_full, df_real.copy(), n_trials=1)

    # 3. Isolation Forest
    iforest = models.get("isolation_forest")
    if iforest is None or getattr(iforest, "n_features_in_", None) != n_features:
        print("⚠️ Retraining Isolation Forest to match dataset dimensions...")
        df_real = train_isolation_forest(X_full, df_real.copy(), n_trials=1)

    # 4. HBOS
    hbos = models.get("hbos")
    if hbos is None or getattr(hbos, "n_features_in_", None) != n_features:
        print("⚠️ Retraining HBOS to match dataset dimensions...")
        df_real = train_hbos(X_full, df_real.copy(), n_trials=1)

    # 5. XGBoost Unsupervised
    xgb = models.get("xgboost_unsupervised")
    if xgb is None or getattr(xgb, "n_features_in_", None) != n_features:
        print("⚠️ Retraining XGBoost Unsupervised to match dataset dimensions...")
        df_real = train_unsupervised_xgboost(X_full, df_real.copy(), n_trials=1)

    # Reload fresh 18-feature models
    models = load_saved_models(input_dim=n_features)
    return models


def run_adversarial_benchmark():
    print("================================================================")
    print("🛡️ RUNNING TABULAR ADVERSARIAL ATTACK & DEFENSE BENCHMARK")
    print("================================================================\n")

    # 1. Load Real Unsupervised Data
    X_full, df_real = load_real_data()
    n_features = X_full.shape[1]

    # 2. Load or Align Pretrained Models
    models = ensure_models_match_dimensions(X_full, df_real, n_features)
    ae_model = models.get("autoencoder", None)

    # 3. BASELINE EVALUATION across a sample to find true model-tagged anomalies
    print("\n--- 1. Baseline Evaluation (Unsupervised Anomaly Discovery) ---")
    sample_size = min(20000, len(X_full))
    X_eval_pool = X_full[:sample_size]
    df_eval_pool = df_real.iloc[:sample_size].copy()

    df_clean_eval = evaluate_ensemble_anomalies(models, X_eval_pool, df_eval_pool)
    
    # Isolate records that the unsupervised ensemble flagged as HIGH RISK (consensus verdict = 1)
    if "ensemble_consensus_verdict" in df_clean_eval.columns:
        anom_mask = (df_clean_eval["ensemble_consensus_verdict"] == 1).values
    else:
        anom_mask = (df_clean_eval.get("eval_anomaly_isolation_forest", pd.Series([0])) == 1).values

    X_anom = X_eval_pool[anom_mask]
    n_anom = len(X_anom)

    if n_anom == 0:
        print("⚠️ No consensus anomalies flagged in the initial sample pool. Lowering threshold or selecting top risk scores...")
        # Fallback to top 1% highest risk records
        risk_scores = df_clean_eval.get("ensemble_risk_score", pd.Series(np.zeros(len(df_clean_eval)))).values
        top_k_idx = np.argsort(risk_scores)[-200:]
        X_anom = X_eval_pool[top_k_idx]
        n_anom = len(X_anom)

    print(f"🎯 Isolated {n_anom} Model-Identified Anomaly Targets for Adversarial Stress Testing!")

    # Reference normal matrix for adversary projection/shield density mapping
    X_normal_ref = X_eval_pool[~anom_mask] if np.sum(~anom_mask) > 0 else X_eval_pool

    # 4. ATTACK WITHOUT DEFENSE (Try to make anomalies pass as benign)
    print("\n--- 2. Attack Execution (WITHOUT Defense) ---")
    adversary = UnifiedTabularAdversary(autoencoder_model=ae_model, normal_ref=X_normal_ref[:10000], epsilon=0.25)
    X_adv = adversary.attack(X_anom)

    df_adv_undefended = evaluate_ensemble_anomalies(models, X_adv, df_eval_pool.iloc[:n_anom].copy())
    
    if "ensemble_consensus_verdict" in df_adv_undefended.columns:
        undefended_detected = int(df_adv_undefended["ensemble_consensus_verdict"].sum())
    else:
        undefended_detected = int((df_adv_undefended.get("eval_anomaly_isolation_forest", pd.Series([0]))).sum())

    evaded_count = n_anom - undefended_detected
    print(f"🚨 Attack Results: {evaded_count}/{n_anom} Anomalies Successfully Evaded Detection! ({evaded_count/max(1, n_anom)*100:.1f}% Evasion Rate)")

    # 5. ATTACK WITH DEFENSE LAYER
    print("\n--- 3. Defense Execution (WITH Tabular Adversarial Shield) ---")
    shield = TabularAdversarialShield(normal_reference_matrix=X_normal_ref[:10000], noise_std=0.05)
    
    defense_output = shield.defend_and_evaluate(models, X_adv)
    X_defended = defense_output["sanitized_features"]
    
    df_adv_defended = evaluate_ensemble_anomalies(models, X_defended, df_eval_pool.iloc[:n_anom].copy())
    
    if "ensemble_consensus_verdict" in df_adv_defended.columns:
        defended_detected = int(df_adv_defended["ensemble_consensus_verdict"].sum())
    else:
        defended_detected = int((df_adv_defended.get("eval_anomaly_isolation_forest", pd.Series([0]))).sum())

    total_protected = min(n_anom, defended_detected + defense_output["n_adversarial_detected"])
    
    print(f"🛡️ Anomalies Re-Captured via Sanitization: {defended_detected}/{n_anom}")
    print(f"🛡️ Adversarial Perturbations Flagged by Shield: {defense_output['n_adversarial_detected']}/{n_anom}")
    print(f"✅ Total Effective Defense Capture Rate: {total_protected}/{n_anom} ({total_protected/max(1, n_anom)*100:.1f}%)")

    # Summary Table
    print("\n================================================================")
    print("📈 BENCHMARK RESULT SUMMARY")
    print("================================================================")
    summary_df = pd.DataFrame({
        "Scenario": ["Clean Model Anomalies", "Attacked (Undefended)", "Attacked (Defended)"],
        "Detection Rate": [
            "100.0% (Baseline Target)",
            f"{undefended_detected/max(1, n_anom)*100:.1f}%",
            f"{total_protected/max(1, n_anom)*100:.1f}%"
        ],
        "Status": ["Baseline", "🚨 Evaded", "🛡️ Protected"]
    })
    print(summary_df.to_string(index=False))


if __name__ == "__main__":
    run_adversarial_benchmark()